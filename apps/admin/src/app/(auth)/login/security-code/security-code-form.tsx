'use client';
import { useEffect, useState, type FormEvent } from 'react';
import { useRouter } from 'next/navigation';
import type { TotpEnrollment } from '@mana/services';
import { Alert } from '@/components/ui/alert';
import { Button } from '@/components/ui/button';
import { Field } from '@/components/ui/field';
import { getBrowserServices } from '@/lib/supabase/browser';

type State =
  | { kind: 'loading' }
  | { kind: 'load_failed'; message: string }
  | { kind: 'needs_setup' }
  | { kind: 'setting_up'; enrollment: TotpEnrollment }
  | { kind: 'verify'; factorId: string };

export function SecurityCodeForm() {
  const router = useRouter();
  const [state, setState] = useState<State>({ kind: 'loading' });
  const [code, setCode] = useState('');
  const [busy, setBusy] = useState(false);
  const [fieldError, setFieldError] = useState<string | undefined>();
  const [formError, setFormError] = useState<string | undefined>();

  async function load() {
    setState({ kind: 'loading' });
    const res = await getBrowserServices().mfa.getStatus();
    if (!res.ok) return setState({ kind: 'load_failed', message: res.error.message });
    setState(
      res.value.verifiedTotpFactorId
        ? { kind: 'verify', factorId: res.value.verifiedTotpFactorId }
        : { kind: 'needs_setup' },
    );
  }

  useEffect(() => {
    void load();
  }, []);

  async function startSetup() {
    setFormError(undefined);
    setBusy(true);
    const res = await getBrowserServices().mfa.enrollTotp();
    setBusy(false);
    if (!res.ok) return setFormError(res.error.message);
    setCode('');
    setState({ kind: 'setting_up', enrollment: res.value });
  }

  async function submit(e: FormEvent) {
    e.preventDefault();
    const factorId =
      state.kind === 'verify'
        ? state.factorId
        : state.kind === 'setting_up'
          ? state.enrollment.factorId
          : null;
    if (!factorId) return;
    setFieldError(undefined);
    setFormError(undefined);
    setBusy(true);
    const res = await getBrowserServices().mfa.verifyTotp(factorId, code.trim());
    if (!res.ok) {
      setBusy(false);
      if (res.error.fields?.['code']) setFieldError(res.error.fields['code']);
      else
        setFormError(
          res.error.code === 'VALIDATION'
            ? 'That code is not correct. Try the newest code.'
            : res.error.message,
        );
      return;
    }
    router.replace('/');
    router.refresh();
  }

  if (state.kind === 'loading') return <p className="text-sm text-neutral-600">Loading…</p>;

  if (state.kind === 'load_failed') {
    return (
      <div className="flex flex-col gap-4">
        <Alert tone="error">{state.message}</Alert>
        <Button variant="secondary" onClick={() => void load()}>
          Try again
        </Button>
      </div>
    );
  }

  if (state.kind === 'needs_setup') {
    return (
      <div className="flex flex-col gap-4">
        {formError ? <Alert tone="error">{formError}</Alert> : null}
        <p className="text-sm text-neutral-700">
          First time here? Install an authenticator app (for example Google Authenticator or
          Microsoft Authenticator) on your phone, then press the button to set it up.
        </p>
        <Button onClick={() => void startSetup()} busy={busy}>
          Set up security code
        </Button>
      </div>
    );
  }

  const codeField = (
    <Field
      id="totp"
      label="6-digit code from the app"
      type="text"
      inputMode="numeric"
      autoComplete="one-time-code"
      maxLength={6}
      value={code}
      onChange={(e) => setCode(e.target.value.replace(/\D/g, ''))}
      error={fieldError}
      required
      autoFocus
    />
  );

  return (
    <form onSubmit={submit} className="flex flex-col gap-4" noValidate>
      {formError ? <Alert tone="error">{formError}</Alert> : null}
      {state.kind === 'setting_up' ? (
        <>
          <p className="text-sm text-neutral-700">Scan this code with your authenticator app.</p>
          {/* QR is an SVG data URL generated by Supabase Auth; no external request. */}
          <img
            src={state.enrollment.qrCode}
            alt="QR code for the authenticator app"
            width={180}
            height={180}
            className="mx-auto rounded border border-neutral-200 bg-white p-2"
          />
          <details className="text-sm text-neutral-600">
            <summary className="cursor-pointer">Can&apos;t scan? Enter this key instead</summary>
            <code className="mt-2 block break-all rounded bg-neutral-100 p-2 font-mono text-xs text-neutral-900">
              {state.enrollment.secret}
            </code>
          </details>
        </>
      ) : null}
      {codeField}
      <Button type="submit" busy={busy}>
        {state.kind === 'setting_up' ? 'Finish setup' : 'Verify'}
      </Button>
    </form>
  );
}
